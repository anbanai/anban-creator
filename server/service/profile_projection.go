var profileDimensionLabels = map[string]string{
	"identity":    "定位、主题边界和差异化",
	"style":       "语言、结构、视觉和表达风格",
	"audience":    "受众、需求和表达深度",
	"platforms":   "平台格式和适配规则",
	"preferences": "偏好、禁用项和合规红线",
	"memory":      "已验证经验和复盘结论",
}

// ProfileDimensionMarkdown is the stable, human-readable projection of one
// structured profile dimension. The database remains authoritative; this
// document is what Agents and Studio users read and edit.
func ProfileDimensionMarkdown(name string, dimension model.ProfileDimension) (string, error) {
	name = strings.TrimSpace(name)
	if _, ok := profileDimensionLabels[name]; !ok {
		return "", fmt.Errorf("unknown profile dimension %q", name)
	}
	if dimension.Content == nil {
		dimension.Content = map[string]any{}
	}
	content, err := json.MarshalIndent(dimension.Content, "", "  ")
	if err != nil {
		return "", fmt.Errorf("marshal profile dimension %s: %w", name, err)
	}
	return fmt.Sprintf("# %s\n\n%s\n\n## 来源\n\n%s\n\n## 证据\n\n%s\n\n## 待补充\n\n%s\n",
		name,
		string(content),
		markdownList(dimension.Sources),
		markdownList(dimension.Evidence),
		markdownList(dimension.MissingFields)), nil
}

// ProfileDimensionMarkdownAtVersion adds a server-owned version marker to a
// rebuildable projection. The marker lets the NAS reject a late retry of an
// older database revision without treating ordinary user Markdown as a
// versioned profile file.
func ProfileDimensionMarkdownAtVersion(name string, dimension model.ProfileDimension, version int64) (string, error) {
	content, err := ProfileDimensionMarkdown(name, dimension)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("<!-- anban-profile-version: %d -->\n%s", version, content), nil
}

func markdownList(values []string) string {
	if len(values) == 0 {
		return "- 无"
	}
	lines := make([]string, 0, len(values))
	for _, value := range values {
		value = strings.TrimSpace(value)
		if value != "" {
			lines = append(lines, "- "+value)
		}
	}
	if len(lines) == 0 {
		return "- 无"
	}
	return strings.Join(lines, "\n")
}

// ProfileAgentsMarkdown is generated by the Server and is never an Agent
// output. Keeping this table server-owned prevents an Agent from changing the
// rules that govern how the profile is consumed.
func ProfileAgentsMarkdown() string {
	return `# AGENTS.md

## 任务入口

本文件是每个 Anban 托管任务工作区的必读入口。Agent 开始任何业务工作前必须先读取本文件，再按下表读取所需的项目画像文件。Server 在每次任务启动时写入当前版本；Agent 不得修改本文件、画像文件或用 Agent memory 替代它们。

## 六维项目画像路由

六个画像文件始终由 Server 一起注入任务工作区。它们是只读事实来源，不是 Agent 的提示词副本。

| 引用路径 | 读取时机 | 用途 |
| --- | --- | --- |
| profile/identity.md | 选题、定位、IP 主张或内容方向 | 定位、主题边界和差异化 |
| profile/style.md | 写作、剪辑、视觉、配音或表达设计 | 语言、结构、视觉和表达风格 |
| profile/audience.md | 钩子、节奏、表达深度、转化和受众判断 | 受众、需求和表达深度 |
| profile/platforms.md | 平台规格、比例、时长、格式、发布或适配 | 平台格式和适配规则 |
| profile/preferences.md | 每个任务都必须读取 | 偏好、形式偏好、明确的禁用项和合规红线 |
| profile/memory.md | 复用经验、历史复盘、归因或恢复任务 | 已验证经验和复盘结论 |

## 路由规则

- 每个任务都必须先读取 AGENTS.md；需要画像时按上表读取相关文件。画像分析 Agent 为了生成完整结果必须读取六个文件。
- Agent 不得在自身提示词、Skill 或输出中复制一套六维画像；不得绕过本文件直接猜测画像路径。
- 明确的禁用项和合规红线是硬约束；普通主题或形式偏好只用于候选排序，不得作为排除条件。
- 一次性或首批内容方向属于有范围的活动偏好，只在其确认的范围内生效；范围结束或需要延长时重新评估，不得无限期沿用。
- 只有用户明确确认的长期定位才作为持续定位。当前任务的明确要求优先于一般偏好。
- [待补充] 和 [推断待确认] 不能当作事实。
- 画像文件不属于 Agent 自动记忆，不要写入 .claude/agent-memory/*/MEMORY.md；Agent 只读它们，不直接写回。
- 数据不足时保留缺失字段，不得编造结论。
`
}

// ProfileAgentsMarkdownForProject keeps the stable profile rules together with
// the project's own instructions. It is written only when the project memory
// directory is initialized and is never regenerated by profile analysis.
func ProfileAgentsMarkdownForProject(instructions string) string {
	content := ProfileAgentsMarkdown()
	if trimmed := strings.TrimSpace(instructions); trimmed != "" {
		content += "\n\n## 项目定位\n\n" + trimmed + "\n"
	}
	return content
}

// ProfileAgentsMarkdownAtVersion is the versioned form used for the
// Server-owned AGENTS.md projection.
func ProfileAgentsMarkdownAtVersion(version int64) string {
	return fmt.Sprintf("<!-- anban-profile-version: %d -->\n%s", version, ProfileAgentsMarkdown())
}

func profileProjectionMatchesVersion(content string, version int64) bool {
	const prefix = "<!-- anban-profile-version: "
	if !strings.HasPrefix(content, prefix) {
		return false
	}
	line, _, _ := strings.Cut(content, "\n")
	value := strings.TrimSuffix(strings.TrimPrefix(line, prefix), " -->")
	parsed, err := strconv.ParseInt(value, 10, 64)
	return err == nil && parsed == version
}
